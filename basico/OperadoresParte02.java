package flamingo.aprendendo.basico;

public class OperadoresParte02 {
    /*
    * < menor que
    * > maior que
    * <= menor ou igual
    * >= maior ou igual
    * == igual a
    * != diferente de
    * */
    public static void main(String[] args) {

        int numero01 = 20;

        System.out.println(numero01 > 30);
        System.out.println(numero01 < 10);
        System.out.println(numero01 <= 21);
        System.out.println(numero01 >= 19);
        System.out.println(numero01 == 20);
        System.out.println(numero01 != 22);

    }
}
